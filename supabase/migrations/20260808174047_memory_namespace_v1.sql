do $$
declare
  target_table text;
  constraint_name text;
begin
  foreach target_table in array array[
    'brain',
    'memories',
    'window_summaries',
    'memory_candidates',
    'active_threads',
    'dream_runs'
  ] loop
    execute format(
      'alter table public.%I add column if not exists space_key text',
      target_table
    );
    execute format(
      'update public.%I set space_key = %L where space_key is null',
      target_table,
      'shared'
    );
    execute format(
      'alter table public.%I alter column space_key set default %L',
      target_table,
      'shared'
    );
    execute format(
      'alter table public.%I alter column space_key set not null',
      target_table
    );

    constraint_name := target_table || '_space_key_fkey';
    if not exists (
      select 1
      from pg_constraint
      where conrelid = format('public.%I', target_table)::regclass
        and conname = constraint_name
    ) then
      execute format(
        'alter table public.%I add constraint %I foreign key (space_key) references public.memory_spaces(space_key) on update cascade on delete restrict',
        target_table,
        constraint_name
      );
    end if;

    execute format(
      'create index if not exists %I on public.%I (space_key)',
      target_table || '_space_key_idx',
      target_table
    );
  end loop;
end
$$;

-- Self-checks. Any failure aborts and rolls back the whole migration.
do $$
declare
  target_table text;
  null_rows bigint;
begin
  if (
    select count(*)
    from public.memory_spaces
    where space_key in ('claude', 'gpt', 'shared')
  ) <> 3 then
    raise exception 'MEMORY-NAMESPACE-V1 verification failed: seed spaces are incomplete';
  end if;

  foreach target_table in array array[
    'brain',
    'memories',
    'window_summaries',
    'memory_candidates',
    'active_threads',
    'dream_runs'
  ] loop
    execute format(
      'select count(*) from public.%I where space_key is null',
      target_table
    ) into null_rows;

    if null_rows > 0 then
      raise exception 'MEMORY-NAMESPACE-V1 verification failed: %.space_key has % null rows', target_table, null_rows;
    end if;
  end loop;
end
$$;

commit;
