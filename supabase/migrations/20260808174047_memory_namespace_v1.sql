-- MEMORY-NAMESPACE-V1
-- Adds one shared memory engine with isolated Claude, GPT, and shared spaces.
-- This migration is intentionally blocked until the P0 owner-only RLS migration
-- has replaced every public allow_all policy on the memory tables.

begin;

do $$
declare
  target_table text;
  missing_tables text[] := '{}';
  insecure_tables text[] := '{}';
  missing_owner_policies text[] := '{}';
begin
  foreach target_table in array array[
    'brain',
    'memories',
    'window_summaries',
    'memory_candidates',
    'active_threads',
    'dream_runs'
  ] loop
    if to_regclass(format('public.%I', target_table)) is null then
      missing_tables := array_append(missing_tables, target_table);
    end if;

    if exists (
      select 1
      from pg_policies
      where schemaname = 'public'
        and tablename = target_table
        and policyname = 'allow_all'
    ) then
      insecure_tables := array_append(insecure_tables, target_table);
    end if;

    if not exists (
      select 1
      from pg_policies
      where schemaname = 'public'
        and tablename = target_table
        and policyname = 'lovehouse_owner_only'
    ) then
      missing_owner_policies := array_append(missing_owner_policies, target_table);
    end if;
  end loop;

  if cardinality(missing_tables) > 0 then
    raise exception 'MEMORY-NAMESPACE-V1 blocked: missing tables: %', array_to_string(missing_tables, ', ');
  end if;

  if cardinality(insecure_tables) > 0 then
    raise exception 'MEMORY-NAMESPACE-V1 blocked: public allow_all policies remain on: %', array_to_string(insecure_tables, ', ');
  end if;

  if cardinality(missing_owner_policies) > 0 then
    raise exception 'MEMORY-NAMESPACE-V1 blocked: owner-only RLS policy missing on: %', array_to_string(missing_owner_policies, ', ');
  end if;
end
$$;

create table public.memory_spaces (
  id bigint generated by default as identity primary key,
  space_key text not null unique,
  owner_id uuid not null references auth.users(id) on delete restrict,
  display_name text not null,
  space_type text not null check (space_type in ('ai', 'shared')),
  owner_model text,
  self_description text,
  speaking_style text,
  memory_strategy text,
  profile_data jsonb not null default '{}'::jsonb
    check (jsonb_typeof(profile_data) = 'object'),
  is_active boolean not null default true,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint memory_spaces_owner_model_check check (
    (space_type = 'shared' and owner_model is null)
    or
    (space_type = 'ai' and owner_model is not null)
  )
);

comment on table public.memory_spaces is
  'LoveHouse memory namespaces and editable AI profile cards. One engine, isolated spaces.';
comment on column public.memory_spaces.profile_data is
  'Forward-compatible profile details; must remain a JSON object.';

